import {readFileSync,writeFileSync,mkdirSync} from 'node:fs';
import {createDecipheriv} from 'node:crypto';
import {spawn} from 'node:child_process';
import {gunzipSync} from 'node:zlib';
import assert from 'node:assert/strict';
assert.equal(process.env.GITHUB_ACTIONS,'true','Cloud runners only');
const scope=process.env.TEST_SCOPE;
assert.ok(['smoke','60','180'].includes(scope));
assert.match(process.env.BUNDLE_KEY||'',/^[a-f0-9]{64}$/);
const partCount=Number(process.env.BUNDLE_PART_COUNT);
assert.ok(Number.isInteger(partCount)&&partCount>0&&partCount<=24,'Missing private test fixture');
const blob=JSON.parse(Array.from({length:partCount},(_,i)=>process.env['BUNDLE_'+String(i).padStart(2,'0')]||'').join(''));
const decipher=createDecipheriv('aes-256-gcm',Buffer.from(process.env.BUNDLE_KEY,'hex'),Buffer.from(blob.iv,'hex'));
decipher.setAuthTag(Buffer.from(blob.tag,'hex'));
const bundle=JSON.parse(gunzipSync(Buffer.concat([decipher.update(Buffer.from(blob.data,'base64')),decipher.final()])).toString());
assert.equal(bundle.fixture.base,'https://snake-party-staging.blue-pond-9237.workers.dev');
assert.equal(bundle.fixture.players,scope==='smoke'?20:800);
assert.equal(bundle.fixture.duration,scope==='180'?180:60);
assert.equal(bundle.fixture.localPlayers,0);
assert.equal(bundle.fixture.minimumSources,4);
mkdirSync('runtime',{recursive:true});
writeFileSync('runtime/fixture.json',JSON.stringify(bundle.fixture),{mode:0o600});
const shard=Number(process.env.SHARD_INDEX);
assert.ok(Number.isInteger(shard)&&shard>=0&&shard<4);
console.log(JSON.stringify({event:'runner',shard,hostedBy:'GitHub Actions',runId:process.env.GITHUB_RUN_ID,runnerName:process.env.RUNNER_NAME,runnerOS:process.env.RUNNER_OS,players:bundle.fixture.players/4,seconds:bundle.fixture.duration}));
const env={...process.env};for(const name of Object.keys(env))if(name.startsWith('BUNDLE_'))delete env[name];
if(shard===0)env.TEST_HOST_KEY=bundle.hostKey;
const child=spawn('./k6',['run','load/test.js'],{env,stdio:['ignore','pipe','pipe']});
let log='';
for(const stream of [child.stdout,child.stderr])stream.on('data',chunk=>{
 const text=chunk.toString();
 if(text.includes(bundle.hostKey))throw new Error('Credential logging forbidden');
 const publicText=text.replaceAll(bundle.fixture.code,'[test-room]');
 log+=publicText;process.stdout.write(publicText);
});
const code=await new Promise((resolve,reject)=>{child.on('error',reject);child.on('exit',resolve)});
writeFileSync('runtime/run.log',log);
writeFileSync('runtime/execution.json',JSON.stringify({scope,shard,players:bundle.fixture.players/4,seconds:bundle.fixture.duration,runId:process.env.GITHUB_RUN_ID,runnerName:process.env.RUNNER_NAME,exitCode:code},null,2));
process.exitCode=typeof code==='number'?code:1;
